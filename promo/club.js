'use strict';
/* The one place the fictional club is named. seed.js, backup.js and the crest
   all derive from CLUB, so renaming the club is a one-line edit here followed
   by `node seed.js` (which rewrites crest/<slug>-crest.svg) and a re-capture.

   The club, its ground, opponents and crest are invented for the film. No real
   club, league or badge is referenced. */

const CLUB = 'Upper Caldecote FC';

/** "Upper Caldecote": the name as it reads in fixture rows and the Wi-Fi SSID. */
const SHORT = CLUB.replace(/\s+FC$/i, '');

/** "upper-caldecote": file-name stem for the crest and the backup. */
const SLUG = SHORT.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const CREST_FILE = `${SLUG}-crest.svg`;
const BACKUP_FILE = `${SLUG}-promo-backup.tar.gz`;

const GREEN = '#157a3b';
const DARK_GREEN = '#0c4f26';
const WHITE = '#ffffff';

const SHIELD = 'M100 8 L186 34 V124 C186 176 150 212 100 232 C50 212 14 176 14 124 V34 Z';

/** The crest as an SVG string: green and white shield, the club name across
 *  the white top band on two lines, hoops, a football and a founding year. */
function crestSvg() {
  const words = SHORT.toUpperCase().split(/\s+/);
  const line1 = words.length > 1 ? words.slice(0, Math.ceil(words.length / 2)).join(' ') : words[0];
  const line2 = words.length > 1 ? words.slice(Math.ceil(words.length / 2)).join(' ') : '';
  const font = 'font-family="Arial, Helvetica, sans-serif" font-weight="800"';
  const text = (y, size, s) =>
    `  <text x="100" y="${y}" text-anchor="middle" ${font} font-size="${size}" fill="${GREEN}" letter-spacing="1.5">${s}</text>`;
  const name = line2
    ? [text(40, 21, line1), text(65, 21, line2)].join('\n')
    : text(52, 26, line1);

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  ${CLUB} — a fictional club invented for the PitchTribe promo video.
  Drawn from scratch for this project; no real club, league or badge is referenced.
  Generated by promo/club.js. Licence: MIT, same as the repository.
  Green ${GREEN}, white ${WHITE}.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 240" width="200" height="240" role="img" aria-label="${CLUB} crest">
  <defs>
    <clipPath id="shield-clip">
      <path d="${SHIELD}"/>
    </clipPath>
  </defs>

  <!-- Shield -->
  <path d="${SHIELD}" fill="${GREEN}"/>

  <!-- Green and white hoops, clipped to the shield -->
  <g clip-path="url(#shield-clip)">
    <rect x="0" y="92" width="200" height="22" fill="${WHITE}"/>
    <rect x="0" y="136" width="200" height="22" fill="${WHITE}"/>
    <rect x="0" y="180" width="200" height="22" fill="${WHITE}"/>
  </g>

  <!-- Top band with the club name -->
  <g clip-path="url(#shield-clip)">
    <rect x="0" y="8" width="200" height="66" fill="${WHITE}"/>
  </g>
${name}

  <!-- Football, drawn from circles and a pentagon -->
  <circle cx="100" cy="124" r="34" fill="${WHITE}" stroke="${GREEN}" stroke-width="4"/>
  <polygon points="100,106 117,118 110,138 90,138 83,118" fill="${GREEN}"/>
  <line x1="100" y1="106" x2="100" y2="92" stroke="${GREEN}" stroke-width="4" stroke-linecap="round"/>
  <line x1="117" y1="118" x2="131" y2="113" stroke="${GREEN}" stroke-width="4" stroke-linecap="round"/>
  <line x1="110" y1="138" x2="119" y2="150" stroke="${GREEN}" stroke-width="4" stroke-linecap="round"/>
  <line x1="90" y1="138" x2="81" y2="150" stroke="${GREEN}" stroke-width="4" stroke-linecap="round"/>
  <line x1="83" y1="118" x2="69" y2="113" stroke="${GREEN}" stroke-width="4" stroke-linecap="round"/>

  <!-- Founded year on the lower hoop -->
  <text x="100" y="197" text-anchor="middle" font-family="Arial, Helvetica, sans-serif" font-size="16" font-weight="700" fill="${GREEN}">EST 1921</text>

  <!-- Outline -->
  <path d="${SHIELD}" fill="none" stroke="${DARK_GREEN}" stroke-width="5" stroke-linejoin="round"/>
</svg>
`;
}

module.exports = { CLUB, SHORT, SLUG, CREST_FILE, BACKUP_FILE, GREEN, crestSvg };
